"""Полномочия без роли администратора (ADR-0013).

Администратор выдаёт сотруднику отдельные полномочия, не делая его администратором; у самого администратора
действуют все. Ключи хранятся в users.capabilities, порядок — как в списке у администратора. Назначать роль
«Администратор», выдавать полномочия, выпускать ключи доступа и настраивать вход через домен может только
администратор.
"""

CAPABILITIES = {
    "system.health": "Смотрит состояние системы",
    "backups.manage": "Ведёт резервное копирование",
    "modules.manage": "Настраивает модули",
    "calendar.manage": "Ведёт производственный календарь",
    "audit.view": "Смотрит реестр изменений",
    "users.manage": "Ведёт учётные записи",
    "org.manage": "Ведёт структуру компании",
    "access.manage": "Выдаёт доступы к проектам",
    "trash.manage": "Управляет корзиной",
}


def known(values):
    """Только известные ключи, без повторов, в порядке списка."""
    own = set(values or []) if isinstance(values, (list, tuple, set)) else set()
    return [key for key in CAPABILITIES if key in own]
